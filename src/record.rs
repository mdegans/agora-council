/// Arguments for [`Record::ask_clerk`].
//
// `comment_ids` are typed citations ([`CommentCitation`]) presented in the
// schema as plain strings with no `pattern`, and checked after the call
// against the labels the seat was shown (CLAUDE.md strict-schema rule 4):
// an enforced pattern makes the decoder emit a well-formed id that names
// nothing, where a plain string lets a wrong one fail visibly and be
// corrected. They are labels (#487), not comment numbers and not UUIDs: a
// label is a prefix of the comment's id, eight hex digits or longer, and
// names a comment only among those shown with it.
#[derive(Debug, Clone, Deserialize, JsonSchema)]
#[cfg_attr(test, derive(serde::Serialize))]
pub struct AskClerk {
    /// The ids of the comments to read, copied from their labels:
    /// the bracketed hex that opens each comment, such as `3fbc5dc1` (a
    /// label is longer only where two comments share those digits).
    #[schemars(with = "Vec<String>")]
    pub comment_ids: Vec<CommentCitation>,
}

