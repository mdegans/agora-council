/// What a councillor submits: the response format of every council
/// conversation, one schema for all of them (see the module docs).
///
/// The two after-vote shapes (`summary`, `summary_review`) are in every
/// conversation's format from its first turn, like `rank` on an item that
/// is not a scheduling item: the format is part of the request a
/// [`CachedPrompt`](misanthropic::prompt::CachedPrompt) fixes for the
/// conversation, and the summary is written in the seat's own
/// conversation, appended (Steward, 2026-10-17). They are legal only when
/// asked for.
#[derive(Debug, Clone, Deserialize, JsonSchema)]
#[serde(tag = "submission")]
#[cfg_attr(test, derive(serde::Serialize))]
pub enum Submission {
    /// Before any round: whether this proposal would limit the Steward's
    /// powers (Constitution Art. IV § 3). Only while the recusal
    /// determination is open.
    #[serde(rename = "determine_recusal")]
    Recusal(DetermineRecusal),
    /// Round 1 only: your independent position and preliminary vote. You
    /// have not yet heard the other councillors.
    #[serde(rename = "position")]
    Position(Position),
    /// Deliberation: respond to the other councillors. Set
    /// `ready_to_vote` when you have nothing further to add.
    #[serde(rename = "respond")]
    Response(Respond),
    /// Your final vote, once the Steward has called it.
    #[serde(rename = "vote")]
    Vote(CastVote),
    /// Scheduling items only, once the Steward has called the vote: your
    /// ranking of the docket.
    #[serde(rename = "rank")]
    Rank(Rank),
    /// After the vote, only when you are asked to write the decision's
    /// summary: your draft, for its reviewers.
    #[serde(rename = "summary")]
    Summary(SummaryDraft),
    /// After the vote, only when you are asked to review the decision's
    /// summary: your review of the Lawyer's draft.
    #[serde(rename = "summary_review")]
    SummaryReview(SeatReview),
}

impl Submission {
    /// The tag the seat wrote
    pub fn name(&self) -> &'static str {
        match self {
            Self::Recusal(_) => "determine_recusal",
            Self::Position(_) => "position",
            Self::Response(_) => "respond",
            Self::Vote(_) => "vote",
            Self::Rank(_) => "rank",
            Self::Summary(_) => "summary",
            Self::SummaryReview(_) => "summary_review",
        }
    }

    /// The response format every seat's conversation carries.
    ///
    /// schemars appends the `submission` tag after a variant's fields;
    /// the format emits properties in order, so it is moved first: the
    /// seat names what it submits, then speaks, then decides. serde reads
    /// the tag wherever it is.
    pub fn output_config() -> misanthropic::prompt::output::OutputConfig {
        use misanthropic::prompt::output::{OutputConfig, schema_for};
        let mut schema = schema_for::<Self>();
        for variant in schema["anyOf"]
            .as_array_mut()
            .expect("an internally tagged enum is an anyOf")
        {
            for key in ["properties", "required"] {
                let field = &mut variant[key];
                *field = match field.take() {
                    serde_json::Value::Object(map) => {
                        let (tag, rest): (Vec<_>, Vec<_>) =
                            map.into_iter().partition(|(k, _)| k == "submission");
                        serde_json::Value::Object(tag.into_iter().chain(rest).collect())
                    }
                    serde_json::Value::Array(items) => {
                        let (tag, rest): (Vec<_>, Vec<_>) =
                            items.into_iter().partition(|v| v == "submission");
                        serde_json::Value::Array(tag.into_iter().chain(rest).collect())
                    }
                    other => other,
                };
            }
        }
        OutputConfig::json_schema(schema)
    }
}

/// Per-councillor tool state: which round the floor is open for, the
/// item's labelled comments (for [`Record::ask_clerk`]), the docket on a
/// scheduling item, and what the last successful method call captured.
/// The harness (`Councillor`) sets [`round`](Self::round) before each
/// exchange and takes [`submission`](Self::submission) and
/// [`lookup`](Self::lookup) after each call.
#[derive(Debug, Default)]
pub struct Record {
    /// The round whose method is currently legal. `None` before the item
    /// opens, and during the recusal determination.
    pub round: Option<RoundType>,
    /// The item's recusal determination is open: `determine_recusal` is
    /// the only legal call, and the harness refuses every read until the
    /// answer is recorded (Constitution Art. IV § 3).
    pub determining: bool,
    /// The item's comments, labelled as the Clerk and the seats were
    /// shown them.
    pub comments: ItemComments,
    /// On a scheduling item, the rankable P-numbers. `None` on every
    /// other item — which is what makes `rank` and `read_proposal`
    /// illegal there.
    pub docket: Option<BTreeMap<u32, PostId>>,
    /// A `read_proposal` the harness must answer: the tool validates the
    /// number, the harness (which holds the transport) asks the Clerk and
    /// writes the result.
    pub lookup: Option<u32>,
    /// What the Clerk read to this seat since the harness last took it,
    /// for the decision's record (#159).
    pub reads: Vec<ClerkRead>,
    /// After the vote: the summary turn the seat is asked for, which is
    /// then the only legal submission, and reads are closed.
    pub after_vote: Option<AfterVote>,
}

/// What a seat is asked for after the vote, in its own conversation
/// (`crate::summary`)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AfterVote {
    /// The Lawyer: the decision's summary (`summary`)
    Summary,
    /// The Artist, Philosopher or Engineer, the Steward recused: a review
    /// of the Lawyer's draft (`summary_review`)
    Review,
}

impl AfterVote {
    /// The submission it asks for
    pub fn submission(self) -> &'static str {
        match self {
            Self::Summary => "summary",
            Self::Review => "summary_review",
        }
    }

    /// The prompt archive's stage name
    pub fn stage(self) -> &'static str {
        match self {
            Self::Summary => "summary",
            Self::Review => "summary_review",
        }
    }
}

/// Something read to a seat mid-deliberation, by the Clerk or through
/// one of the seat's agent tools
#[derive(Debug, Clone)]
pub enum ClerkRead {
    /// `ask_clerk`: comments read back verbatim, as the seat received
    /// them, with the labels of the comments read
    Comments { labels: Vec<String>, text: String },
    /// `read_proposal`: a docket proposal and the Clerk's summary of its
    /// thread, as the seat received them
    Proposal { number: u32, content: Content },
    /// A call to one of the seat's agent tools
    /// ([`SeatTools`](crate::seat_tools::SeatTools), e.g. `get_content`):
    /// the tool, its arguments as the seat sent them, and the whole result
    /// as the seat received it, refusals included
    Tool {
        name: String,
        arguments: serde_json::Value,
        result: Content,
        is_error: bool,
    },
}

impl Record {
    /// Tool state for one agenda item, holding its labelled comments and,
    /// on a scheduling item, its docket.
    pub fn new(comments: impl Into<ItemComments>, docket: Option<BTreeMap<u32, PostId>>) -> Self {
        Self {
            round: None,
            determining: false,
            comments: comments.into(),
            docket,
            lookup: None,
            reads: Vec::new(),
            after_vote: None,
        }
    }

    /// Check a ranking against the docket. Every failure names what to
    /// fix, so the seat can correct it on the next sample.
    fn validate(docket: &BTreeMap<u32, PostId>, args: &Rank) -> Result<(), String> {
        if args.ranking.is_empty() {
            return Err("Rank at least one proposal.".into());
        }
        if args.sitting_capacity == 0 {
            return Err("`sitting_capacity` must be at least 1.".into());
        }
        let mut seen = std::collections::BTreeSet::new();
        for number in &args.ranking {
            if !docket.contains_key(number) {
                return Err(format!(
                    "P{number} is not on the docket. Rank by the P-numbers \
                     listed (P1–P{}); D-numbered posts cannot be ranked.",
                    docket.len()
                ));
            }
            if !seen.insert(*number) {
                return Err(format!("P{number} appears twice in your ranking."));
            }
        }
        Ok(())
    }
}

/// A retired positional reference (`C12`, `[C12]`), which a seat trained on
/// older records might still reach for.
fn looks_positional(cited: &str) -> bool {
    let cited = agora_common::clerk::normalize_citation(cited);
    cited
        .strip_prefix('c')
        .is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit()))
}

/// Declared property orders of every [`Submission`], from the live
/// output schema: the emission contract `Councillor::exchange` enforces on
/// each submission, the `submission` tag first.
///
/// Structured outputs emit an object's properties in `properties` order;
/// that is verified implementation behavior for strict tools (2026-08-14),
/// not documented. When it stops being true the statement can follow the
/// decision, so the sitting stops instead. (blallama guarantees this by
/// grammar; its responses pass trivially.)
pub fn declared_orders() -> &'static [(String, Vec<String>)] {
    static ORDERS: std::sync::OnceLock<Vec<(String, Vec<String>)>> = std::sync::OnceLock::new();
    ORDERS.get_or_init(|| {
        let config = serde_json::to_value(Submission::output_config()).expect("schemas serialize");
        config["format"]["schema"]["anyOf"]
            .as_array()
            .expect("the submission schema is an anyOf of its variants")
            .iter()
            .map(|variant| {
                let props = variant["properties"]
                    .as_object()
                    .expect("every submission has properties");
                let name = props["submission"]["const"]
                    .as_str()
                    .expect("every submission is tagged")
                    .to_string();
                (name, props.keys().cloned().collect())
            })
            .collect()
    })
}

/// What a seat is told when it reads during a summary turn: the summary is
/// written from the record it was given, which is what will be signed.
pub const READS_CLOSED_AFTER_VOTE: &str = "Reads are closed for the summary: work from the \
     decision's record in the message above, which is what will be signed.";

/// What a seat is told when it submits anything but `determine_recusal`
/// during the recusal determination.
pub const DETERMINATION_FIRST: &str = "This item opens with the recusal determination, before any round: \
     submit `determine_recusal`. The rounds open once the four answers are \
     recorded.";

impl Record {
    /// Whether a read can run: during the recusal determination, or once an
    /// item is on the floor. Reads are open at the determination since
    /// 2026-10-17 (Steward): a seat decides on what is before the Council,
    /// and may read any of it, the whole thread included.
    fn reads_open(&self) -> Result<(), Content> {
        if self.after_vote.is_some() {
            return Err(READS_CLOSED_AFTER_VOTE.into());
        }
        if self.determining || self.round.is_some() {
            Ok(())
        } else {
            Err("No item is on the floor.".into())
        }
    }
}

impl Record {
    /// Check `submission` is legal now. Every refusal names what to submit
    /// instead, so the seat can correct it on the next sample.
    pub fn submit(&self, submission: &Submission) -> Result<(), String> {
        const NO_ITEM: &str = "No item is on the floor.";
        const CALLED: &str = "The Steward has called the vote. Submit `vote`.";
        const ROUND_1: &str = "The vote has not been called. This is Round 1: submit `position`.";
        const DELIBERATING: &str = "The vote has not been called. Continue deliberating: submit \
             `respond` (set `ready_to_vote` when you are ready).";
        if self.determining {
            return match submission {
                Submission::Recusal(_) => Ok(()),
                _ => Err(DETERMINATION_FIRST.into()),
            };
        }
        if let Some(asked) = self.after_vote {
            return match (asked, submission) {
                (AfterVote::Summary, Submission::Summary(_)) => Ok(()),
                (AfterVote::Review, Submission::SummaryReview(_)) => Ok(()),
                (asked, _) => Err(format!(
                    "The vote is over: you are asked for the decision's summary. Submit `{}`.",
                    asked.submission()
                )),
            };
        }
        match (submission, self.round) {
            (Submission::Summary(_) | Submission::SummaryReview(_), _) => Err(
                "`summary` and `summary_review` are for after the vote, when you are \
                 asked for them. Submit for the round."
                    .into(),
            ),
            (Submission::Recusal(_), _) => Err("This item's recusal determination is already \
                 recorded. Submit `position`, `respond` or `vote` for the round."
                .into()),
            (_, None) => Err(NO_ITEM.into()),
            (Submission::Position(_), Some(RoundType::Independent)) => Ok(()),
            (Submission::Position(_), Some(RoundType::Deliberation)) => Err(
                "Round 1 is over: the Council is deliberating. Engage the other \
                     councillors: submit `respond`."
                    .into(),
            ),
            (Submission::Response(_), Some(RoundType::Deliberation)) => Ok(()),
            (Submission::Response(_), Some(RoundType::Independent)) => {
                Err("This is Round 1, independent analysis: submit `position` first.".into())
            }
            (Submission::Vote(_), Some(RoundType::FinalVote)) if self.docket.is_some() => Err(
                "This is a scheduling item: the Council ranks the docket rather \
                     than voting on it. Submit `rank`."
                    .into(),
            ),
            // Every final vote is recorded with its statement, and an
            // abstention's statement is the one-sentence rationale Art. IV
            // § 3 requires (agentkit `Votes::from_final_round`). Asked for
            // here, while the seat can still give one, rather than failing
            // at signing.
            (Submission::Vote(v), Some(RoundType::FinalVote))
                if Statement::try_from(v.statement.as_str()).is_err() =>
            {
                Err(match v.vote {
                    FinalVote::Abstain => {
                        "An abstention is recorded with a one-sentence \
                         rationale (Constitution Art. IV § 3): give it as your `statement`."
                    }
                    FinalVote::Yes | FinalVote::No | FinalVote::Defer => {
                        "Your final vote is recorded with \
                         its `statement`, and yours is blank: give it."
                    }
                }
                .into())
            }
            (Submission::Vote(_), Some(RoundType::FinalVote)) => Ok(()),
            (Submission::Rank(_), _) if self.docket.is_none() => {
                Err("`rank` is only for scheduling items. On this item, submit \
                     `position`, `respond` or `vote` for the round."
                    .into())
            }
            (Submission::Rank(args), Some(RoundType::FinalVote)) => {
                Self::validate(self.docket.as_ref().expect("checked above"), args)
            }
            (Submission::Position(_) | Submission::Response(_), Some(RoundType::FinalVote)) => {
                Err(CALLED.into())
            }
            (Submission::Vote(_) | Submission::Rank(_), Some(RoundType::Independent)) => {
                Err(ROUND_1.into())
            }
            (Submission::Vote(_) | Submission::Rank(_), Some(RoundType::Deliberation)) => {
                Err(DELIBERATING.into())
            }
        }
    }
}

#[tool(name = "record", flat, strict)]
impl Record {
    /// Ask the Clerk to read specific comments from the proposal's thread
    /// verbatim into the record, by the ids their labels show. You may then
    /// continue your turn.
    // TODO(clerk): free-form questions answered by the Clerk (Haiku) from
    // its raw context — this method currently only reads comments back.
    #[method]
    async fn ask_clerk(&mut self, args: AskClerk) -> Result<Content, Content> {
        self.reads_open()?;
        if self.comments.is_empty() {
            return Err("This item has no comment thread for the Clerk to read from.".into());
        }
        if args.comment_ids.is_empty() {
            return Err("Name the ids of the comments to read, copied from their \
                 labels (the bracketed hex that opens each comment)."
                .into());
        }

        let mut s = String::new();
        let mut labels = Vec::new();
        for cited in &args.comment_ids {
            let id = match cited.resolve(&self.comments.labels) {
                LabelMatch::One(id) => id,
                LabelMatch::Many(ids) => {
                    let options: Vec<String> = ids
                        .iter()
                        .map(|id| format!("[{}]", self.comments.label(*id)))
                        .collect();
                    return Err(format!(
                        "`{cited}` starts {} comments' ids: {}. Ask for one by \
                         its full label.",
                        ids.len(),
                        options.join(", ")
                    )
                    .into());
                }
                LabelMatch::None => {
                    let hint = if looks_positional(cited.as_str()) {
                        " Comments are no longer numbered: each is cited by the id \
                         in its label."
                    } else {
                        ""
                    };
                    return Err(format!(
                        "No comment on this item has the id `{cited}`. Copy the id \
                         from the comment's label, such as `3fbc5dc1`; `ask_clerk` \
                         reads this item's threads only.{hint}"
                    )
                    .into());
                }
            };
            let Some(comment) = self.comments.get(id) else {
                return Err(format!("The Clerk could not find `{cited}`.").into());
            };
            let label = self.comments.label(id);
            // A comment from a related thread says which (#492).
            let on = match self.comments.thread_of(id) {
                Some(thread) if thread.role == agora_common::council::ThreadRole::Related => {
                    format!(" on the related thread {}", thread.name())
                }
                Some(_) | None => String::new(),
            };
            let _ = write!(
                s,
                "[{label}] {} wrote{on}:\n{}\n\n",
                comment.author, comment.body
            );
            labels.push(label);
        }
        let text = s.trim_end().to_string();
        self.reads.push(ClerkRead::Comments {
            labels,
            text: text.clone(),
        });
        Ok(text.into())
    }

    /// Scheduling items only. Have the Clerk read a docket proposal to you:
    /// its full text and a summary of its comment thread. You may then
    /// continue your turn.
    #[method]
    async fn read_proposal(&mut self, args: ReadProposal) -> Result<Content, Content> {
        self.reads_open()?;
        let Some(docket) = &self.docket else {
            return Err("`read_proposal` is only for scheduling items; this item \
                 has no docket."
                .into());
        };
        if !docket.contains_key(&args.number) {
            return Err(format!(
                "There is no P{} on the docket (P1–P{}).",
                args.number,
                docket.len()
            )
            .into());
        }
        self.lookup = Some(args.number);
        // Replaced by the harness with what the Clerk read.
        Ok(format!("The Clerk is reading P{}.", args.number).into())
    }
}

