/// A vote in the opening round, where `defer` is still available.
///
/// Emitted **inline** rather than as a `$ref` into `$defs`.
///
/// **Treat `$ref` as broken on Anthropic surfaces regardless of what the
/// docs say.** It is listed as supported for structured outputs, and it
/// has failed us twice anyway:
///
/// 1. The Claude.ai MCP connector *drops parameter values* whose schema is
///    a `$ref` — which is why `agora-agentkit`'s `define_id!` writes an
///    inline `JsonSchema` impl for every newtype ID.
/// 2. On 2026-08-01 `vote` was the only `$ref`-schema'd field in this
///    tool, the only constrained field, and the only one that came back
///    contradicting every text field in its own call.
///
/// `#[schemars(inline)]` is schemars' own mechanism for this, and it
/// derives the variant list from the enum. This used to be a hand-written
/// `JsonSchema` impl generated by a local macro that took the variants as
/// string literals — so `["yes", "no", "abstain", "defer"]` sat beside
/// the enum with nothing checking the two agreed, and adding a variant
/// would have silently left it out of the schema the model is shown. That
/// is the same defect as a `json!` schema kept in step with its struct by
/// hand, which is exactly what we removed from the redaction tool.
///
/// misanthropic ≥ alpha.16 also inlines subschemas in
/// `sanitize_for_anthropic`, so this is now belt and braces — but the
/// braces are one attribute rather than forty lines, and the MCP surface
/// (rmcp + schemars, no misanthropic in the path) has no belt at all.
/// `strict_is_on_and_vote_enums_are_inlined` holds both ends.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, JsonSchema)]
#[serde(rename_all = "lowercase")]
#[schemars(inline)]
#[cfg_attr(test, derive(serde::Serialize))]
pub enum OpeningVote {
    Yes,
    No,
    Abstain,
    Defer,
}

impl From<OpeningVote> for CouncilVote {
    fn from(v: OpeningVote) -> Self {
        match v {
            OpeningVote::Yes => CouncilVote::Yes,
            OpeningVote::No => CouncilVote::No,
            OpeningVote::Abstain => CouncilVote::Abstain,
            OpeningVote::Defer => CouncilVote::Defer,
        }
    }
}

