        record.round = Some(RoundType::Independent);
        let ask = |ids: &[&str]| call("toolu_ask", "ask_clerk", input(ask_for(ids)));

        let result = record.call(ask(&["[A3DCBEA6]", "3fbc5dc1-d6"])).await;
        assert!(!result.is_error, "{}", result.content);
        let text = result.content.to_string();
