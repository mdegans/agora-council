//! How councillors speak into the record.
//!
//! A seat thinks, then submits a [`Submission`]: the response format
//! (`output_config`) of its conversation, one schema whose variants are
//! the recusal determination, `position` (round 1), `respond`
//! (deliberation), `vote` and `rank` (the final round). Before it submits
//! it may read, through the `record` tool's methods `ask_clerk` (comments
//! from the item's threads, verbatim, by label, #487) and `read_proposal`
//! (a docket proposal), and through the agent tools.
//!
//! ## Why thinking, and no `reasoning` field (2026-10-07)
//!
//! Until 2026-10 every decision method carried a `reasoning` field,
//! declared first and kept first by `strict` (the constrained decoder
//! emits fields in declaration order; Haiku jurors, unconstrained, put
//! their verdict first on APP-2026-0003). Asking a model to write its
//! reasoning into a field is what Anthropic's `reasoning_extraction`
//! safeguard declines ("a `reasoning`, `thinking`, or `trace` field in
//! JSON output or in a tool input"), and the Steward treats it as a terms
//! of service risk. The seats now think before they answer, which puts
//! the reasoning before the decision by construction, and the record
//! keeps what the API returns for that thinking (agentkit's `Rationale`):
//! on Anthropic models a summary written by Anthropic, signed.
//!
//! Each submission still carries words for the record (`position`,
//! `response`, the vote's `statement`, an `explanation`), and its decision
//! last; `schema_guard` holds the order.
//!
//! ## One schema, `tool_choice: auto`
//!
//! Forcing a tool call (`ToolChoice::Any`) is rejected under budgeted
//! thinking and on the newest models, so the seat chooses between a read
//! and its submission (`tool_choice: auto`), and the format is what keeps
//! its turn structured. The format, tools and tool
//! choice stay constant for the whole conversation: each is part of the
//! cache key. Which submission is *legal* is enforced by
//! [`Record::submit`] instead: an out-of-round submission is answered
//! with what to submit, and the harness re-samples, append-only.
//!
//! No schema here may carry `$ref` (the 2026-08-01 corruption; CLAUDE.md),
//! so the vote enums are inlined, and `agora_common::schema_guard`
//! refuses any prompt whose tools or format carry one regardless.
//!
//! `defer` is only offered where it is legal: it exists in
//! [`OpeningVote`] (round 1) and [`FinalVote`] (the final vote, since
//! 2026-10-17: two or more seats deferring send the item to a later
//! sitting, agentkit 0.97's `FinalVotes::outcome`), and is structurally
//! absent from [`StandingVote`], the deliberation rounds' vote.

